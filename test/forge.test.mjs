import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

import { SKILL_DESTINATION, forge, parseStamp, version } from "../index.js";
import { resolveOutputPath, writeSkill } from "../lib/output.js";

const fixture = path.join(path.dirname(fileURLToPath(import.meta.url)), "fixture");
const tmpRepo = () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "forge-fixture-"));
  fs.cpSync(fixture, dir, { recursive: true });
  return dir;
};

test("parseStamp reads a Forge stamp and rejects anything else", () => {
  const s = parseStamp("x\n<!-- generated: 2026-11-20 | rules: abc | schema: 3 | sdks: openai_sdk, mcp | template: 2 -->\n");
  assert.deepEqual(s.sdks, ["openai_sdk", "mcp"]);
  assert.equal(s.template, 2);
  assert.equal(parseStamp("# hand-written skill"), null);
});

test("writes stay inside the repository and never replace a hand-written file", () => {
  const dir = tmpRepo();
  try {
    assert.throws(() => resolveOutputPath(dir, "../outside.md"), /not a file inside/);
    fs.mkdirSync(path.join(dir, "docs"));
    fs.writeFileSync(path.join(dir, "docs", "SKILL.md"), "# mine");
    assert.throws(() => writeSkill(dir, "docs/SKILL.md", "new"), /not generated by Forge/);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test("forge() rejects a missing target", async () => {
  await assert.rejects(forge(""), /repository directory/);
});

// Downloads and verifies the real analyzer binary, then generates and writes the skill for the fixture repo.
test("generates a skill end to end", { timeout: 300_000 }, async () => {
  assert.match(await version(), /\d+\.\d+\.\d+/);
  const dir = tmpRepo();
  try {
    const r = await forge(dir, { outputPath: SKILL_DESTINATION });
    assert.ok(r.stamp, "the skill carries a Forge stamp");
    assert.ok(r.sdks.length >= 1, `expected a detected SDK, got ${JSON.stringify(r.sdks)}`);
    assert.equal(fs.readFileSync(r.written, "utf8"), r.skill);
    // Regenerating replaces the file Forge wrote.
    assert.equal((await forge(dir, { outputPath: SKILL_DESTINATION })).written, r.written);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
